/** Texto de uma chave no idioma pedido, com interpolação `{nome}`. */
export function t(lang: Lang, key: EngineScheduleKey, args?: Record<string, string | number>): string {
  const text = dictFor(lang)[key] ?? EN[key] ?? PT[key];
  if (!args) return text;
  return text.replace(/\{(\w+)\}/g, (all, name: string) => (name in args ? String(args[name]) : all));
}

/** Collation da ordenação de textos do idioma. */
export function collationFor(lang: Lang = 'pt'): string {
  switch (lang) {
    case 'en': return 'en';
    case 'es': return 'es';
    case 'de': return 'de';
    case 'fr': return 'fr';
    case 'it': return 'it';
    case 'pl': return 'pl';
    default: return 'pt-BR';
  }
}

/** Símbolo decimal do idioma (usado quando o projeto não sobrescreveu o das unidades). */
export function decimalSymbolFor(lang: Lang = 'pt'): ',' | '.' {
  return lang === 'en' ? '.' : ',';
}

