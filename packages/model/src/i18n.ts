/** Nome de tipo de abertura traduzido (medidas com vírgula viram ponto em EN). */
export function openingName(name: string, lang: Lang = 'pt'): string {
  if (lang === 'pt') return name;
  const coluna = { en: 1, es: 2, de: 3, fr: 4, it: 5, pl: 6 } as const;
  let text = name;
  for (const row of OPENING_NAME_BLOCKS) text = text.split(row[0]).join(row[coluna[lang]] ?? row[0]);
  if (lang === 'en') text = text.replace(/(\d),(\d)/g, '$1.$2');
  return text;
}

