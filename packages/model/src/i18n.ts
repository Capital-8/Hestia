/** Nome de tipo de abertura traduzido (medidas com vírgula viram ponto em EN). */
export function openingName(name: string, lang: Lang = 'pt'): string {
  if (lang !== 'en') return name;
  let text = name;
  for (const [pt, en] of OPENING_NAME_BLOCKS) text = text.split(pt).join(en);
  return text.replace(/(\d),(\d)/g, '$1.$2');
}

