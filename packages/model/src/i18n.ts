/** Texto de uma chave no idioma pedido, com interpolação `{nome}`. */
export function t(lang: Lang = 'pt', key: Key, args?: Record<string, string | number>): string {
  const text = (lang === 'en' ? EN : PT)[key];
  if (!args) return text;
  return text.replace(/\{(\w+)\}/g, (all, name: string) => (name in args ? String(args[name]) : all));
}

/** Símbolo decimal do idioma (usado quando o projeto não sobrescreveu o das unidades). */
export function decimalSymbolFor(lang: Lang = 'pt'): ',' | '.' {
  return lang === 'en' ? '.' : ',';
}

/** Texto no idioma: `pt` devolve o próprio texto (dados antigos não mudam). */
export function textFor(lang: Lang, pt: string, en: string): string {
  return lang === 'en' ? en : pt;
}

