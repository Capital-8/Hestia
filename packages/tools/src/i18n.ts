/** Texto da chave no idioma pedido, com interpolação `{nome}`. EN ausente cai em PT; nunca devolve `undefined`. */
export function t(lang: Lang, key: DictKey, args?: Record<string, string | number>): string {
  const text = (lang === 'en' ? EN[key] : PT[key]) ?? PT[key];
  if (!args) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in args ? String(args[name]) : whole));
}

/** Idioma do ambiente da ferramenta (`env.lang?.() ?? 'pt'`). */
export function langOf(env: { lang?: () => Lang }): Lang {
  return env.lang?.() ?? 'pt';
}

/** Número com casas fixas e o separador do idioma (PT: vírgula; EN: ponto). */
export function fmtNumLang(value: number, decimals: number, lang: Lang): string {
  const text = Math.abs(value).toFixed(decimals); // units-ok: formatação do idioma do pacote (o separador decimal vem de `lang`)
  return lang === 'en' ? text : text.replace('.', ',');
}

