import { chromium } from 'playwright-core';
import { CHROME_ARGS, chromeExecutable } from './helpers.mjs';
const b = await chromium.launch({ executablePath: chromeExecutable(), args: CHROME_ARGS });
const page = await (await b.newContext({ viewport: { width: 1400, height: 800 } })).newPage();
await page.goto('http://127.0.0.1:5211/?debug=1');
await page.waitForFunction(() => window.__hestia, null, { timeout: 180000 });
await page.getByRole('button', { name: /Novo projeto/ }).first().click();
await page.waitForSelector('.canvas-wrap canvas', { timeout: 180000 });
await page.evaluate(() => {
  const { editor, model, engine, useUi } = window.__hestia;
  const nivel = useUi.getState().levelId;
  for (const id of ['fam_krona_esgoto_tubo_corte', 'fam_krona_esgoto_joelho90']) editor.store.exec({ type: 'upsertFamily', family: structuredClone(model.familiaDaBiblioteca(id)) });
  editor.store.transaction('carga', () => { for (let i = 0; i < 900; i++) { const a = [(i % 20) * 1.2, Math.floor(i / 20), 0.5]; const c = engine.trechoDeTubo(a, [a[0] + 1, a[1], 0.5], { id: 'fam_krona_esgoto_tubo_corte' }, 100, { id: `t${i}`, levelId: nivel }); editor.store.exec({ type: 'addComponent', component: c }); if (i % 2 === 0) editor.store.exec({ type: 'addComponent', component: { id: `j${i}`, kind: 'component', familyId: 'fam_krona_esgoto_joelho90', typeId: 'dn100', levelId: nivel, order: 0, x: a[0] + 1, y: a[1], z: 0.5, rotation: 0, mirrored: false, mark: '' } }); } });
  editor.zoomFit?.();
});
await page.waitForTimeout(1500);
const cdp = await page.context().newCDPSession(page);
await cdp.send('Profiler.enable');
await cdp.send('Profiler.start');
await page.evaluate(() => { const c = document.querySelector('.canvas-wrap canvas'); const r = c.getBoundingClientRect(); for (let i = 0; i < 400; i++) c.dispatchEvent(new PointerEvent('pointermove', { clientX: r.x + 200 + ((i * 37) % 800), clientY: r.y + 150 + ((i * 53) % 400), bubbles: true, pointerId: 1 })); });
const { profile } = await cdp.send('Profiler.stop');
const self = new Map();
const dt = profile.timeDeltas; const ids = profile.samples;
const nodes = new Map(profile.nodes.map((n) => [n.id, n]));
ids.forEach((id, i) => { const n = nodes.get(id); const k = `${n.callFrame.functionName || '(anon)'} ${n.callFrame.url.split('/').slice(-2).join('/')}:${n.callFrame.lineNumber}`; self.set(k, (self.get(k) ?? 0) + (dt[i] ?? 0)); });
const tot = [...self.values()].reduce((a, b) => a + b, 0);
console.log('total ms', Math.round(tot / 1000));
for (const [k, v] of [...self.entries()].sort((a, b) => b[1] - a[1]).slice(0, 14)) console.log(String(Math.round(v / 1000)).padStart(6), 'ms', k);
await b.close();
